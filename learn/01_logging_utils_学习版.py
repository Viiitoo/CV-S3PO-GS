"""
文件：01_logging_utils_学习版.py
功能：学习日志打印工具模块
难度：⭐（最简单，适合入门）
学习目标：
1. 理解模块导入（import）
2. 理解字典（dict）的定义和使用
3. 理解函数定义和调用
4. 理解条件判断（if语句）
5. 理解字典的方法（keys()）
6. 理解可变参数（*args）和默认参数
7. 理解字符串格式化（f-string）

这个文件的作用是：提供彩色日志打印功能，让程序运行时的输出更美观易读
"""

# ============ 知识点1：模块导入 ============
# import 语句用来导入其他模块（库、包）的功能
# rich 是一个第三方库，用于美化终端输出（颜色、样式等）
import rich


# ============ 知识点2：全局变量和字典 ============
# _log_styles 是一个字典（dict），用来存储不同标签对应的样式
# 字典的格式：{键1: 值1, 键2: 值2, ...}
# 这里的键是字符串（标签名），值也是字符串（颜色样式）
# 注意：变量名前的下划线 _ 表示这是一个模块内部使用的变量（约定俗成）
_log_styles = {
    "S3PO-GS": "bold green",   # "S3PO-GS" 标签使用 粗体绿色
    "GUI": "bold magenta",      # "GUI" 标签使用 粗体洋红色
    "Eval": "bold red",         # "Eval" 标签使用 粗体红色
}


# ============ 知识点3：函数定义 ============
# def 关键字用来定义函数
# 函数名：get_style
# 参数：tag（标签名，字符串类型）
# 返回值：样式字符串
def get_style(tag):
    """
    根据标签获取对应的样式
    
    参数：
        tag: 字符串，表示日志标签（如 "S3PO-GS"、"GUI"）
    
    返回值：
        字符串，表示样式（如 "bold green"）
    """
    # ============ 知识点4：条件判断和字典方法 ============
    # if 语句用于条件判断
    # tag in _log_styles.keys() 检查 tag 是否在字典的键（keys）中
    # .keys() 方法返回字典的所有键
    if tag in _log_styles.keys():
        # 如果找到了，返回对应的样式值
        # _log_styles[tag] 通过键访问字典的值
        return _log_styles[tag]
    
    # 如果没找到，返回默认样式（粗体蓝色）
    # return 语句用于返回函数的结果
    return "bold blue"


# ============ 知识点5：函数定义（带默认参数和可变参数） ============
# def Log(*args, tag="S3PO-GS"):
#   - *args: 可变参数，可以传入任意多个参数，它们会被打包成元组
#   - tag="S3PO-GS": 默认参数，如果不传tag，默认值是"S3PO-GS"
def Log(*args, tag="S3PO-GS"):
    """
    打印带颜色的日志信息
    
    参数：
        *args: 可变参数，可以传入任意多个要打印的内容
              例如：Log("Hello", "World") 或 Log("Error occurred")
        tag: 日志标签，用于选择不同的颜色样式（默认是"S3PO-GS"）
    
    示例：
        Log("程序启动")  # 使用默认tag="S3PO-GS"，绿色粗体
        Log("GUI初始化", tag="GUI")  # 使用tag="GUI"，洋红色粗体
        Log("第", 1, "步", "完成")  # 可以传多个参数
    """
    # 调用上面定义的 get_style 函数，获取对应标签的样式
    style = get_style(tag)
    
    # ============ 知识点6：字符串格式化和函数调用 ============
    # f-string 是Python的字符串格式化方法，f"..." 中的 {变量} 会被替换为变量的值
    # rich.print() 是rich库的打印函数，可以打印带样式的文本
    # [style] 和 [/style] 是rich库的标记语法，用来设置文本样式
    # *args 前面的 * 表示解包，把元组展开成多个参数传给函数
    # 例如：args = ("Hello", "World")，*args 相当于 "Hello", "World"
    rich.print(f"[{style}]{tag}:[/{style}]", *args)


# ============ 测试示例（这部分代码不会在模块导入时执行） ============
# 只有在直接运行这个文件时才会执行（if __name__ == "__main__"）
if __name__ == "__main__":
    # 测试不同的日志打印
    print("=== 测试日志打印功能 ===")
    Log("这是默认标签的日志")  # 会显示为绿色粗体
    Log("这是GUI模块的日志", tag="GUI")  # 会显示为洋红色粗体
    Log("这是评估模块的日志", tag="Eval")  # 会显示为红色粗体
    Log("这是未知标签的日志", tag="Unknown")  # 会显示为蓝色粗体（默认样式）
    Log("可以", "传入", "多个", "参数", "它们会自动拼接")
